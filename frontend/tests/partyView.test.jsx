import { act, renderHook, waitFor } from "@testing-library/react";
import { expect, it, vi } from "vitest";
import useParty from "../src/components/party/useParty";
vi.mock("../src/services/tabSession", () => ({tabFetch: vi.fn(() => Promise.resolve({json:async()=>({})}))}));
it("preserves an independent view on reactions, but regroups on host navigation and transfer", async () => {
  const handlers = {};
  const socket = {connected:true, on:vi.fn((name,fn)=>{handlers[name]=fn;}),off:vi.fn(),emit:vi.fn()};
  const props = {room:{id:"room"},participant:{id:"guest"},socket,onPartyChange:vi.fn(),onPartyEnded:vi.fn(),onHostChange:vi.fn(),initialProductId:"linked"};
  const {result} = renderHook(()=>useParty(props));
  const base={version:1,status:"live",mode:"host",currentProductId:"one",imageIndex:0,hostParticipantId:"host"};
  act(()=>handlers["party:state"]({state:base}));
  await waitFor(()=>expect(result.current.localId).toBe("linked"));
  act(()=>handlers["party:state"]({state:{...base,version:2}}));
  expect(result.current.localId).toBe("linked");
  act(()=>handlers["party:state"]({state:{...base,version:3},force:true}));
  expect(result.current.localId).toBeNull();
  const explore={...base,version:4,mode:"explore"};
  act(()=>handlers["party:state"]({state:explore}));
  act(()=>{result.current.setLocalId("two");result.current.setImage(1);});
  act(()=>handlers["party:state"]({state:{...explore,version:5}}));
  expect(result.current.localId).toBe("two");
  expect(result.current.image).toBe(1);
  act(()=>handlers["party:state"]({state:{...explore,version:5,currentProductId:"new-shared-product"}}));
  expect(result.current.localId).toBe("two");
  expect(result.current.image).toBe(1);
  act(()=>handlers["party:peers"]({views:{friend:{productId:"three",imageIndex:0}},following:{guest:"friend"}}));
  expect(result.current.followView.productId).toBe("three");
  act(()=>handlers["party:state"]({state:{...base,version:6,currentProductId:"four"}}));
  expect(result.current.localId).toBeNull();
  expect(result.current.followView).toBeNull();
  act(()=>handlers["party:state"]({state:{...explore,version:7}}));
  act(()=>result.current.setLocalId("two"));
  act(()=>handlers["party:state"]({state:{...explore,version:8,hostParticipantId:"guest"}}));
  expect(result.current.localId).toBeNull();
});
